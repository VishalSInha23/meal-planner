import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";
import { brandSchema, type BrandConfig } from "../src/config/brand-schema.ts";

// Run with Node's built-in TypeScript support: relative imports carry the .ts extension.

export interface FontFamilies {
  sans: string;
  serif: string;
}

export interface FontPackage {
  pkg: string;
  // The font-family name the package registers in its CSS.
  family: string;
  // The CSS the package is imported with.
  importPath: string;
}

export interface GenerateOptions {
  configDir: string;
  publicDir: string;
  outDir: string;
  nodeModulesDir: string;
  log?: (message: string) => void;
}

const header = "// Generated by scripts/generate-brand.ts from config/brand.json. Do not edit.\n";

export function formatBrandIssues(error: z.ZodError): string {
  return error.issues.map((issue) => `  ${issue.path.join(".") || "(file)"}: ${issue.message}`).join("\n");
}

export function readBrandConfig(configDir: string): { brand: BrandConfig; file: string } {
  const real = join(configDir, "brand.json");
  const file = existsSync(real) ? real : join(configDir, "brand.example.json");
  let json: unknown;
  try {
    json = JSON.parse(readFileSync(file, "utf8"));
  } catch (error) {
    throw new Error(`Cannot read ${file}: ${error instanceof Error ? error.message : String(error)}`, { cause: error });
  }
  const result = brandSchema.safeParse(json);
  if (!result.success) {
    throw new Error(`Invalid brand config ${file}:\n${formatBrandIssues(result.error)}`);
  }
  return { brand: result.data, file };
}

export function fontSlug(name: string): string {
  return name.trim().toLowerCase().replace(/\s+/g, "-");
}

// Maps a font name to its Fontsource package: the variable package first, then the static one.
export function resolveFontPackage(name: string, isInstalled: (pkg: string) => boolean): FontPackage {
  const slug = fontSlug(name);
  const variable = `@fontsource-variable/${slug}`;
  if (isInstalled(variable)) return { pkg: variable, family: `${name} Variable`, importPath: variable };
  const fixed = `@fontsource/${slug}`;
  if (isInstalled(fixed)) return { pkg: fixed, family: name, importPath: fixed };
  throw new Error(
    `Font "${name}" is not installed. Run: npm i --save-exact ${variable}\n` +
      `(if that font has no variable version, install the static one instead: npm i --save-exact ${fixed})`,
  );
}

export function buildBrandTs(brand: BrandConfig, families: FontFamilies): string {
  return (
    header +
    `import type { BrandConfig } from "../brand-schema.ts";\n\n` +
    `export const brand: BrandConfig & { fontFamilies: { sans: string; serif: string } } = ${JSON.stringify({ ...brand, fontFamilies: families }, null, 2)};\n`
  );
}

export function buildFontsTs(packages: FontPackage[]): string {
  const imports = [...new Set(packages.map((font) => font.importPath))];
  return header + imports.map((path) => `import ${JSON.stringify(path)};\n`).join("");
}

function cssFamily(family: string, fallback: string): string {
  return `${JSON.stringify(family)}, ${fallback}`;
}

export function buildBrandCss(brand: BrandConfig, families: FontFamilies): string {
  const { light, dark } = brand.colors;
  const colors = (mode: { ink: string; paper: string }, scheme: string, indent: string) =>
    `${indent}--ink: ${mode.ink};\n${indent}--paper: ${mode.paper};\n${indent}color-scheme: ${scheme};\n`;
  return `/* Generated by scripts/generate-brand.ts from config/brand.json. Do not edit. */
:root,
[data-theme="light"] {
${colors(light, "light", "  ")}}

[data-theme="dark"] {
${colors(dark, "dark", "  ")}}

@media (prefers-color-scheme: dark) {
  html:not([data-theme]) {
${colors(dark, "dark", "    ")}  }
}

:root {
  --font-sans: ${cssFamily(families.sans, "system-ui, sans-serif")};
  --font-serif: ${cssFamily(families.serif, "Georgia, serif")};
}

[data-font="serif"] body {
  font-family: var(--font-serif);
}

[data-font="sans"] body {
  font-family: var(--font-sans);
}
`;
}

export function generateBrand(options: GenerateOptions): { file: string } {
  const log = options.log ?? console.log;
  const { brand, file } = readBrandConfig(options.configDir);
  log(`brand: using ${file}`);

  if (!existsSync(join(options.publicDir, brand.icon))) {
    throw new Error(`Invalid brand config ${file}:\n  icon: ${brand.icon} does not exist in public/`);
  }

  const isInstalled = (pkg: string) => existsSync(join(options.nodeModulesDir, pkg, "package.json"));
  const sans = resolveFontPackage(brand.fonts.sans, isInstalled);
  const serif = resolveFontPackage(brand.fonts.serif, isInstalled);
  const families = { sans: sans.family, serif: serif.family };

  mkdirSync(options.outDir, { recursive: true });
  writeFileSync(join(options.outDir, "brand.ts"), buildBrandTs(brand, families));
  writeFileSync(join(options.outDir, "brand-fonts.ts"), buildFontsTs([sans, serif]));
  writeFileSync(join(options.outDir, "brand.css"), buildBrandCss(brand, families));
  return { file };
}

if (import.meta.main) {
  const root = process.cwd();
  try {
    generateBrand({
      configDir: join(root, "config"),
      publicDir: join(root, "public"),
      outDir: join(root, "src", "config", "generated"),
      nodeModulesDir: join(root, "node_modules"),
    });
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
