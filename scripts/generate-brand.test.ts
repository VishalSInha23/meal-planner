import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import {
  buildBrandCss,
  buildFontsTs,
  fontSlug,
  generateBrand,
  readBrandConfig,
  resolveFontPackage,
} from "./generate-brand.ts";

const example = JSON.parse(readFileSync("config/brand.example.json", "utf8"));
const families = { sans: "Inter Variable", serif: "Source Serif 4 Variable" };

describe("resolveFontPackage", () => {
  it("maps a font name to its variable Fontsource package", () => {
    const installed = () => true;
    expect(resolveFontPackage("Source Serif 4", installed)).toEqual({
      pkg: "@fontsource-variable/source-serif-4",
      family: "Source Serif 4 Variable",
      importPath: "@fontsource-variable/source-serif-4",
    });
    expect(resolveFontPackage("Inter", installed).family).toBe("Inter Variable");
  });

  it("falls back to the static package when the variable one is missing", () => {
    expect(resolveFontPackage("Lora", (pkg) => pkg === "@fontsource/lora")).toEqual({
      pkg: "@fontsource/lora",
      family: "Lora",
      importPath: "@fontsource/lora",
    });
  });

  it("names the exact npm command when neither package is installed", () => {
    expect(() => resolveFontPackage("Fira Sans", () => false)).toThrow(
      "npm i --save-exact @fontsource-variable/fira-sans",
    );
  });

  it("builds the slug from lowercase words joined by dashes", () => {
    expect(fontSlug("  Source Serif 4 ")).toBe("source-serif-4");
  });
});

describe("generated files", () => {
  it("writes the css variables for light, dark and no chosen theme and both fonts", () => {
    const css = buildBrandCss(example, families);
    expect(css).toContain('[data-theme="dark"] {\n  --ink: #F4F3EE;\n  --paper: #1F1E1D;');
    expect(css).toContain('@media (prefers-color-scheme: dark) {\n  html:not([data-theme]) {\n    --ink: #F4F3EE;');
    expect(css).not.toContain('data-theme="system"');
    expect(css).toContain('--font-serif: "Source Serif 4 Variable", Georgia, serif;');
    expect(css).toContain('[data-font="sans"] body {\n  font-family: var(--font-sans);');
  });

  it("imports each font package once", () => {
    const font = { pkg: "p", family: "P", importPath: "p" };
    expect(buildFontsTs([font, font])).toBe(
      "// Generated by scripts/generate-brand.ts from config/brand.json. Do not edit.\nimport \"p\";\n",
    );
  });
});

describe("generateBrand", () => {
  let dir: string;
  const options = () => ({
    configDir: join(dir, "config"),
    publicDir: join(dir, "public"),
    outDir: join(dir, "out"),
    nodeModulesDir: join(process.cwd(), "node_modules"),
    log: (message: string) => logged.push(message),
  });
  let logged: string[];

  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), "brand-"));
    logged = [];
    mkdirSync(join(dir, "config"));
    mkdirSync(join(dir, "public/brand"), { recursive: true });
    cpSync("public/brand/icon.svg", join(dir, "public/brand/icon.svg"));
    cpSync("config/brand.example.json", join(dir, "config/brand.example.json"));
  });

  afterEach(() => rmSync(dir, { recursive: true, force: true }));

  it("falls back to the example file and says so", () => {
    const { file } = generateBrand(options());
    expect(file).toBe(join(dir, "config/brand.example.json"));
    expect(logged).toEqual([`brand: using ${file}`]);
    for (const name of ["brand.ts", "brand-fonts.ts", "brand.css"]) {
      expect(existsSync(join(dir, "out", name))).toBe(true);
    }
    expect(readFileSync(join(dir, "out/brand-fonts.ts"), "utf8")).toContain('import "@fontsource-variable/inter";');
  });

  it("prefers config/brand.json when it exists", () => {
    writeFileSync(
      join(dir, "config/brand.json"),
      JSON.stringify({ ...example, colors: { ...example.colors, light: { ink: "#000000", paper: "#ffffff" } } }),
    );
    const { file } = generateBrand(options());
    expect(file).toBe(join(dir, "config/brand.json"));
    expect(readFileSync(join(dir, "out/brand.css"), "utf8")).toContain("--paper: #ffffff;");
  });

  it("names the field of an invalid file", () => {
    writeFileSync(join(dir, "config/brand.json"), JSON.stringify({ ...example, colors: { ...example.colors, dark: { ink: "x", paper: "#000000" } } }));
    expect(() => readBrandConfig(join(dir, "config"))).toThrow("colors.dark.ink");
  });

  it("fails when the icon is not in public/", () => {
    writeFileSync(join(dir, "config/brand.json"), JSON.stringify({ ...example, icon: "/brand/missing.svg" }));
    expect(() => generateBrand(options())).toThrow("icon: /brand/missing.svg does not exist in public/");
  });
});
